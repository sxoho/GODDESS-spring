BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE PRODUCT_COLOR_IMAGE CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP SEQUENCE PRODUCT_COLOR_IMAGE_SEQ';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -2289 THEN RAISE; END IF;
END;
/

CREATE SEQUENCE PRODUCT_COLOR_IMAGE_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE PRODUCT_COLOR_IMAGE (
    COLORIMAGE_ID     NUMBER          NOT NULL,
    PRODUCTCOLOR_ID   NUMBER          NOT NULL,
    FILE_ORIGIN       VARCHAR2(255)   NOT NULL,
    FILE_SAVED        VARCHAR2(255)   NOT NULL,
    FILE_PATH         VARCHAR2(500)   NOT NULL,
    IS_MAIN           CHAR(1)         DEFAULT 'N' NOT NULL,
    IMAGE_TYPE        VARCHAR2(30)    NOT NULL,
    SORT_ORDER        NUMBER          DEFAULT 1 NOT NULL,
    CREATED_AT        DATE            DEFAULT SYSDATE NOT NULL,

    CONSTRAINT PK_PRODUCT_COLOR_IMAGE PRIMARY KEY (COLORIMAGE_ID),
    CONSTRAINT FK_COLOR_IMAGE_PRODUCT_COLOR
        FOREIGN KEY (PRODUCTCOLOR_ID)
        REFERENCES PRODUCT_COLOR (PRODUCTCOLOR_ID),
    CONSTRAINT CK_COLOR_IMAGE_MAIN
        CHECK (IS_MAIN IN ('Y', 'N'))
);

COMMENT ON TABLE PRODUCT_COLOR_IMAGE IS '상품 색상별 이미지';
COMMENT ON COLUMN PRODUCT_COLOR_IMAGE.COLORIMAGE_ID IS '색상 이미지 번호';
COMMENT ON COLUMN PRODUCT_COLOR_IMAGE.PRODUCTCOLOR_ID IS '상품 색상 번호';
COMMENT ON COLUMN PRODUCT_COLOR_IMAGE.FILE_ORIGIN IS '원본 파일명';
COMMENT ON COLUMN PRODUCT_COLOR_IMAGE.FILE_SAVED IS '저장 파일명';
COMMENT ON COLUMN PRODUCT_COLOR_IMAGE.FILE_PATH IS '저장 경로';
COMMENT ON COLUMN PRODUCT_COLOR_IMAGE.IS_MAIN IS '대표 이미지 여부(Y/N)';
COMMENT ON COLUMN PRODUCT_COLOR_IMAGE.IMAGE_TYPE IS '이미지 종류(MAIN/DETAIL/THUMBNAIL/TRYON)';
COMMENT ON COLUMN PRODUCT_COLOR_IMAGE.SORT_ORDER IS '출력 순서';
COMMENT ON COLUMN PRODUCT_COLOR_IMAGE.CREATED_AT IS '등록일';


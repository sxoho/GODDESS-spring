SELECT
    PC.PRODUCTCOLOR_ID,
    PC.PRODUCT_ID,
    PCM.COLOR_NAME,
    PCM.COLOR_CODE,
    PC.IS_MAIN,
    PC.SORT_ORDER,
    PC.AI_APPLY_ENABLED,
    PC.VISIBLE
FROM PRODUCT_COLOR PC
JOIN PRODUCT_COLOR_MASTER PCM
  ON PC.COLOR_ID = PCM.COLOR_ID
ORDER BY PC.PRODUCT_ID, PC.SORT_ORDER, PC.PRODUCTCOLOR_ID;

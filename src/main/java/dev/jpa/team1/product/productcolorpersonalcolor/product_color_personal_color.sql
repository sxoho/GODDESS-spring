-- 색상별 추천 퍼스널컬러 매핑
CREATE TABLE PRODUCT_COLOR_PERSONAL_COLOR (
    PCPC_ID NUMBER       NOT NULL,
    PRODUCTCOLOR_ID                 NUMBER       NOT NULL,
    PERSONAL_COLOR_TYPE             VARCHAR2(20) NOT NULL,

    CONSTRAINT PK_PCPC
        PRIMARY KEY (PCPC_ID),
    CONSTRAINT FK_PCPC_PRODUCT_COLOR
        FOREIGN KEY (PRODUCTCOLOR_ID) REFERENCES PRODUCT_COLOR(PRODUCTCOLOR_ID),
    CONSTRAINT UK_PCPC_COLOR_TYPE
        UNIQUE (PRODUCTCOLOR_ID, PERSONAL_COLOR_TYPE),
    CONSTRAINT CK_PCPC_TYPE
        CHECK (PERSONAL_COLOR_TYPE IN ('SPRING_WARM', 'SUMMER_COOL', 'AUTUMN_WARM', 'WINTER_COOL', 'NEUTRAL'))
);

CREATE SEQUENCE PCPC_SEQ
START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

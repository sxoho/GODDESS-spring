BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE PRODUCT CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP SEQUENCE PRODUCT_SEQ';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -2289 THEN RAISE; END IF;
END;
/

CREATE SEQUENCE PRODUCT_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE PRODUCT (
    PRODUCT_ID         NUMBER          NOT NULL,
    CATEGORY_ID        NUMBER          NOT NULL,
    NAME               VARCHAR2(200)   NOT NULL,
    DESCRIPTION        CLOB            NULL,
    PRICE              NUMBER          DEFAULT 0 NOT NULL,
    DISCOUNT           NUMBER          DEFAULT 0 NULL,
    BRAND              VARCHAR2(100)   NULL,
    USAGE_INFO         VARCHAR2(500)   NULL,
    AI_APPLY_ENABLED   CHAR(1)         DEFAULT 'Y' NOT NULL,
    PRODUCT_TYPE       VARCHAR2(30)    NULL,
    VOLUME             VARCHAR2(50)    NULL,
    SKIN_TYPE          VARCHAR2(100)   NULL,
    STATUS             VARCHAR2(20)    DEFAULT 'ON_SALE' NOT NULL,
    VIEW_COUNT         NUMBER          DEFAULT 0 NOT NULL,
    CREATED_AT         DATE            DEFAULT SYSDATE NOT NULL,
    UPDATED_AT         DATE            NULL,

    CONSTRAINT PK_PRODUCT PRIMARY KEY (PRODUCT_ID),
    CONSTRAINT FK_PRODUCT_CATEGORY
        FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORY (CATEGORY_ID),
    CONSTRAINT CK_PRODUCT_AI_APPLY
        CHECK (AI_APPLY_ENABLED IN ('Y', 'N')),
    CONSTRAINT CK_PRODUCT_PRICE
        CHECK (PRICE >= 0),
    CONSTRAINT CK_PRODUCT_DISCOUNT
        CHECK (DISCOUNT IS NULL OR DISCOUNT >= 0),
    CONSTRAINT CK_PRODUCT_VIEW_COUNT
        CHECK (VIEW_COUNT >= 0)
);

COMMENT ON TABLE PRODUCT IS '뷰티 상품';
COMMENT ON COLUMN PRODUCT.PRODUCT_ID IS '상품 번호';
COMMENT ON COLUMN PRODUCT.CATEGORY_ID IS '카테고리 번호';
COMMENT ON COLUMN PRODUCT.NAME IS '상품명';
COMMENT ON COLUMN PRODUCT.DESCRIPTION IS '상품 설명';
COMMENT ON COLUMN PRODUCT.PRICE IS '기본 가격';
COMMENT ON COLUMN PRODUCT.DISCOUNT IS '할인율(%)';
COMMENT ON COLUMN PRODUCT.BRAND IS '브랜드';
COMMENT ON COLUMN PRODUCT.USAGE_INFO IS '사용 방법';
COMMENT ON COLUMN PRODUCT.AI_APPLY_ENABLED IS 'AI 뷰티 적용 가능 여부(Y/N)';
COMMENT ON COLUMN PRODUCT.PRODUCT_TYPE IS '상품 유형(LIP, EYE, BLUSH, BASE 등)';
COMMENT ON COLUMN PRODUCT.VOLUME IS '용량/중량';
COMMENT ON COLUMN PRODUCT.SKIN_TYPE IS '추천 피부 타입';
COMMENT ON COLUMN PRODUCT.STATUS IS '판매 상태';
COMMENT ON COLUMN PRODUCT.VIEW_COUNT IS '조회수';
COMMENT ON COLUMN PRODUCT.CREATED_AT IS '등록일';
COMMENT ON COLUMN PRODUCT.UPDATED_AT IS '수정일';


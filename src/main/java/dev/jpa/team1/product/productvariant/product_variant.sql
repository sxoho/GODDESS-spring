BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE PRODUCT_VARIANT CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP SEQUENCE PRODUCT_VARIANT_SEQ';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -2289 THEN RAISE; END IF;
END;
/

CREATE SEQUENCE PRODUCT_VARIANT_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE PRODUCT_VARIANT (
    PRODUCTVARIANT_ID     NUMBER          NOT NULL,
    PRODUCT_ID            NUMBER          NOT NULL,
    VARIANT_NAME          VARCHAR2(50)    NOT NULL,
    VARIANT_DESCRIPTION   VARCHAR2(255)   NULL,
    VISIBLE               CHAR(1)         DEFAULT 'Y' NOT NULL,
    SORT_ORDER            NUMBER          DEFAULT 1 NOT NULL,

    CONSTRAINT PK_PRODUCT_VARIANT PRIMARY KEY (PRODUCTVARIANT_ID),
    CONSTRAINT FK_PRODUCT_VARIANT_PRODUCT
        FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT (PRODUCT_ID),
    CONSTRAINT CK_PRODUCT_VARIANT_VISIBLE
        CHECK (VISIBLE IN ('Y', 'N'))
);

COMMENT ON TABLE PRODUCT_VARIANT IS '상품 규격/호수/용량 옵션';
COMMENT ON COLUMN PRODUCT_VARIANT.PRODUCTVARIANT_ID IS '상품 규격 번호';
COMMENT ON COLUMN PRODUCT_VARIANT.PRODUCT_ID IS '상품 번호';
COMMENT ON COLUMN PRODUCT_VARIANT.VARIANT_NAME IS '규격명';
COMMENT ON COLUMN PRODUCT_VARIANT.VARIANT_DESCRIPTION IS '규격 설명';
COMMENT ON COLUMN PRODUCT_VARIANT.VISIBLE IS '사용 여부(Y/N)';
COMMENT ON COLUMN PRODUCT_VARIANT.SORT_ORDER IS '출력 순서';


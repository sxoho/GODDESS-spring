CREATE SEQUENCE PRODUCT_COLOR_MASTER_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE PRODUCT_COLOR_MASTER (
    COLOR_ID     NUMBER         NOT NULL,
    COLOR_NAME   VARCHAR2(50)   NOT NULL,
    COLOR_CODE   VARCHAR2(20)   NOT NULL,

    CONSTRAINT PK_PRODUCT_COLOR_MASTER PRIMARY KEY (COLOR_ID)
);

